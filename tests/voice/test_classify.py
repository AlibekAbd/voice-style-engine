# --- порции внутри регистра -----------------------------------------------


def test_a_portion_holds_only_people_of_one_register():
    куски = [("Санжар", "свои", "текст-1"), ("Тимур", "формальное", "текст-2"),
             ("Марат", "свои", "текст-3")]

    порции = classify.portions(куски, "свои", потолок=10**6)

    assert [кто for кто, _ in порции[0]] == ["Санжар", "Марат"]


def test_the_parts_of_one_person_stay_together():
    # Части одного собеседника не разлучаются, пока он влезает в потолок:
    # разложив их по разным порциям, получим несколько сводов об одном
    # человеке и ни одного о нём целиком.
    куски = [("Нурлан", "свои", "а" * 40), ("Тимур", "свои", "б" * 40),
             ("Нурлан", "свои", "в" * 40)]

    порции = classify.portions(куски, "свои", потолок=10**6)

    свои = [номер for номер, порция in enumerate(порции)
            for кто, _ in порция if кто == "Нурлан"]
    assert len(set(свои)) == 1
    # И идут подряд, а не вперемешку с чужими.
    кто_где = [кто for порция in порции for кто, _ in порция]
    assert кто_где == ["Нурлан", "Нурлан", "Тимур"]


def test_a_person_heavier_than_the_ceiling_gets_his_own_portions():
    # Один человек может давать три четверти регистра «свои». Смешав его с прочими, получим свод
    # о нём, названный сводом о группе.
    куски = [("Нурлан", "свои", "а" * 400), ("Тимур", "свои", "б" * 10)]

    порции = classify.portions(куски, "свои", потолок=20)

    чужие = [порция for порция in порции if any(кто != "Нурлан" for кто, _ in порция)]
    assert all(all(кто != "Нурлан" for кто, _ in порция) for порция in чужие)


# --- вес блока считает скрипт ---------------------------------------------


НИЖНИЙ = """### Приветствие

Сведён из:
- «Салем» (Санжар): здоровается коротко
- «Привет» (Тимур): здоровается

Определение: здоровается
"""

ВЕРХНИЙ = """### Приветствие и смолл-ток

Сведён из:
- «Приветствие» (свод «низ-1»): здоровается
- «Приветствие» (свод «низ-2»): здоровается

Определение: здоровается
"""


def test_the_weight_of_a_block_is_counted_through_the_levels():
    # Верхний свод перечисляет нижние своды, а не людей: вес собеседников на
    # верхнем уровне терялся. У «приятельского» вышло по одному-двум
    # источникам на блок вместо десятков — счёт агенту не поручается.
    низ = {"низ-1": НИЖНИЙ, "низ-2": НИЖНИЙ.replace("Санжар", "Ваня").replace("Тимур", "Петя")}

    вес = classify.weights(ВЕРХНИЙ, низ)

    assert вес["Приветствие и смолл-ток"] == {"Санжар", "Тимур", "Ваня", "Петя"}


def test_a_lower_merge_is_recognised_however_the_agent_named_it():
    # Один агент написал «(свод «низ-1»)», другой просто «(низ-1)», третий
    # пошёл сразу до людей. Разбирается по факту: если в скобках имя нижнего
    # свода — идём по цепочке, иначе там человек.
    верхний = ВЕРХНИЙ.replace('свод «низ-1»', 'низ-1').replace('свод «низ-2»', 'низ-2')
    низ = {"низ-1": НИЖНИЙ, "низ-2": НИЖНИЙ.replace("Санжар", "Ваня").replace("Тимур", "Петя")}

    вес = classify.weights(верхний, низ)

    assert вес["Приветствие и смолл-ток"] == {"Санжар", "Тимур", "Ваня", "Петя"}


def test_a_block_of_the_lower_level_keeps_its_own_people():
    вес = classify.weights(НИЖНИЙ, {})

    assert вес["Приветствие"] == {"Санжар", "Тимур"}


def test_a_third_way_of_naming_a_merge_is_still_a_merge():
    # «(свод низ-1)» без ёлочек превращал свод в человека: вес блока выходил
    # единицей вместо десятков, молча.
    верх = ("### Привет\n\nСведён из:\n"
            "- «Привет» (свод низ-1): здоровается\n")
    ниже = {"низ-1": "### Привет\n\nСведён из:\n- «Привет» (Санжар): здоровается\n"}

    вес = classify.weights(верх, ниже)

    assert вес["Привет"] == {"Санжар"}
