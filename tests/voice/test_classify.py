"""Классификация собеседников по типу отношений.

Ось сведения. Первый заход резал описания по алфавиту и весу, и группы
существовали только главой внутри свода — сводить по ним было нельзя.

Один агент читает карточки всех собеседников и раздаёт классы. Выделенные заданы
до агента: самый плотный даёт больше половины материала, и его манеру нельзя
называть манерой класса.

Проверка — отдельные агенты по сырой выгрузке, а не по карточкам: карточку
писал агент первого шага, и проверять её ею же значит проверять агента им самим.
"""

import pytest

from tgservice.voice import classify

ОПИСАНИЕ_СОЛО = """Это часть 1 из 1, период с 2025-09-24 по 2026-08-26.

## 1. Кто собеседник владельцу и что от этого меняется в тоне

Собеседник — близкий друг и брат по вере. Владелец обращается «брат», «ахи».

## 2. Блоки речевых действий владельца

### Исламское приветствие
Владелец отвечает полными формулами.

### Согласие и подтверждение
Владелец соглашается коротко.

## 3. Раскладка сообщений владельца по блокам

2025-09-24 14:28 я: Уа-алейкум ас-салям
"""

ОПИСАНИЕ_СБОРНОЕ = """Это сборный батч из 2 переписок.

## Собеседник 1 из 2: Руслан (@ruslan_k)

### 1. Кто собеседник владельцу и что от этого меняется в тоне
Старший коллега. Владелец на «вы», обращение «Руслан-ага».

### 2. Блоки речевых действий владельца

#### Приветствие
Здоровается уважительно.

### 3. Раскладка сообщений владельца по блокам

## Собеседник 2 из 2: Тимур (@timur_dev)

### 1. Кто собеседник владельцу и что от этого меняется в тоне
Подрядчик по видео. Сугубо деловые отношения.

### 2. Блоки речевых действий владельца

#### Постановка задачи
Ставит задачи прямо.

### 3. Раскладка сообщений владельца по блокам
"""

ИНДЕКС = [
    {"file": "sanzhar_b-1.md", "kind": "solo", "chat_id": "11", "chat": "Санжар Брат",
     "chats": [{"id": "11", "name": "Санжар Брат", "msgs": 400}]},
    {"file": "сборный-01.md", "kind": "tail", "chat_id": None, "chat": None,
     "chats": [{"id": "22", "name": "Руслан", "msgs": 40},
               {"id": "33", "name": "Тимур", "msgs": 20}]},
]

ОПИСАНИЯ = {"sanzhar_b-1.md": ОПИСАНИЕ_СОЛО, "сборный-01.md": ОПИСАНИЕ_СБОРНОЕ}


# --- карточки -------------------------------------------------------------


def test_every_interlocutor_gets_a_card():
    карточки = classify.cards(ОПИСАНИЯ, ИНДЕКС)

    assert [к["имя"] for к in карточки] == ["Санжар Брат", "Руслан (@ruslan_k)", "Тимур (@timur_dev)"]


def test_people_are_keyed_by_chat_not_by_name():
    # За именем «.» в выгрузке стоят четыре разных чата, за «Мадина» — два.
    # Ключ по имени склеивал их в одного человека.
    индекс = [{"file": "сборный-01.md", "kind": "tail", "chat_id": None, "chat": None,
               "chats": [{"id": "22", "name": "Руслан", "msgs": 40},
                         {"id": "33", "name": "Тимур", "msgs": 20}]},
              {"file": "сборный-02.md", "kind": "tail", "chat_id": None, "chat": None,
               "chats": [{"id": "44", "name": "Руслан", "msgs": 9},
                         {"id": "55", "name": "Другой", "msgs": 9}]}]
    описания = {"сборный-01.md": ОПИСАНИЕ_СБОРНОЕ,
                "сборный-02.md": ОПИСАНИЕ_СБОРНОЕ.replace("Руслан (@ruslan_k)", "Руслан")}

    карточки = classify.cards(описания, индекс)

    assert [к["чат"] for к in карточки] == ["22", "33", "44", "55"]


def test_the_name_in_the_description_is_checked_against_the_index():
    # Позиция «Собеседник 3 из 20» указывает на третий чат батча. Если агент
    # переставил их местами, позиция врёт — и это надо назвать, а не проглотить.
    индекс = [{"file": "сборный-01.md", "kind": "tail", "chat_id": None, "chat": None,
               "chats": [{"id": "22", "name": "Кто-то другой", "msgs": 40},
                         {"id": "33", "name": "Тимур", "msgs": 20}]}]

    карточки = classify.cards({"сборный-01.md": ОПИСАНИЕ_СБОРНОЕ}, индекс)

    assert карточки[0]["разошлось"] == ("Руслан (@ruslan_k)", "Кто-то другой")
    assert карточки[1]["разошлось"] is None


def test_a_card_carries_the_portrait_the_agent_wrote():
    карточки = classify.cards(ОПИСАНИЯ, ИНДЕКС)

    assert "близкий друг и брат по вере" in карточки[0]["портрет"]
    assert "Старший коллега" in карточки[1]["портрет"]


def test_a_card_carries_the_names_of_the_speech_blocks():
    # По блокам видно отношения не хуже, чем по портрету: «Исламское
    # приветствие» и «Постановка задачи» — разные отношения.
    карточки = classify.cards(ОПИСАНИЯ, ИНДЕКС)

    assert карточки[0]["блоки"] == ["Исламское приветствие", "Согласие и подтверждение"]
    assert карточки[2]["блоки"] == ["Постановка задачи"]


def test_the_layout_chapter_does_not_leak_into_the_blocks():
    # Названия блоков повторяются в раскладке. Взяв и их, получим дубли.
    карточки = classify.cards(ОПИСАНИЯ, ИНДЕКС)

    assert карточки[0]["блоки"].count("Исламское приветствие") == 1


def test_the_parts_of_one_person_become_one_card():
    # У самого плотного собеседника тридцать частей, у редкого четыре. Классифицируется человек, а не
    # часть переписки.
    индекс = ИНДЕКС + [{"file": "sanzhar_b-2.md", "kind": "solo", "chat_id": "11",
                        "chat": "Санжар Брат",
                        "chats": [{"id": "11", "name": "Санжар Брат", "msgs": 400}]}]
    описания = dict(ОПИСАНИЯ, **{"sanzhar_b-2.md": ОПИСАНИЕ_СОЛО.replace(
        "близкий друг и брат по вере", "деловой партнёр")})

    карточки = classify.cards(описания, индекс)

    свои = [к for к in карточки if к["чат"] == "11"]
    assert len(свои) == 1
    assert "близкий друг" in свои[0]["портрет"] and "деловой партнёр" in свои[0]["портрет"]


def test_the_script_counts_the_messages_not_the_agent():
    # Сколько сообщений — механическое, у агента это не спрашивают. И считается
    # по выгрузке, а не по индексу: в индексе `msgs` стоит на часть, и у собеседника
    # с тридцатью частями вышло бы 427 вместо 40 000.
    карточки = classify.cards(ОПИСАНИЯ, ИНДЕКС, счёт={"11": 1240})

    assert карточки[0]["сообщений"] == 1240


# --- лист агенту ----------------------------------------------------------


def test_the_sheet_numbers_the_cards():
    # Ссылка номером, а не именем: имя агент перепечатывает руками и портит.
    # Это известное лекарство, которое к цитатам применить не успели.
    лист = classify.sheet(classify.cards(ОПИСАНИЯ, ИНДЕКС))

    assert "1. Санжар Брат" in лист
    assert "3. Тимур" in лист


def test_the_sheet_carries_portrait_and_blocks():
    лист = classify.sheet(classify.cards(ОПИСАНИЯ, ИНДЕКС))

    assert "близкий друг и брат по вере" in лист
    assert "Постановка задачи" in лист


