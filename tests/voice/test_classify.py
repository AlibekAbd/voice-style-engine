def test_the_answer_is_read_back_by_number():
    ответ = "1 | Санжар Брат | близкий друг\n3 | Тимур | подрядчик\n2 | Руслан | старший\n"

    роздано = classify.assignments(ответ)

    assert роздано == {1: "близкий друг", 2: "старший", 3: "подрядчик"}


def test_a_line_out_of_format_is_skipped_not_guessed():
    ответ = "1 | Санжар | друг\nтут агент рассуждает вслух\n2 | Руслан | старший\n"

    assert classify.assignments(ответ) == {1: "друг", 2: "старший"}


