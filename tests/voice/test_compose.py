def test_a_replacement_finds_the_quote_by_its_text_not_by_the_whole_line():
    # Агент присылает «БЫЛО» без отметки времени — он видит цитату, а не
    # строку файла. Требуя строку целиком, не вклеили ни одной из двадцати
    # двух правок.
    файл = "Примеры:\n2025-11-17 05:11 я: Айгерим, добрый день !\n"
    правки = {"Айгерим, добрый день !": "<имя>, добрый день !"}

    вышло = compose.impersonal(файл, правки)

    assert "2025-11-17 05:11 я: <имя>, добрый день !" in вышло


def test_a_replacement_does_not_touch_a_line_it_was_not_meant_for():
    файл = "2025-11-17 05:11 я: салем\n2025-11-18 06:00 я: салем брат\n"
    правки = {"салем брат": "салем <обращение>"}

    вышло = compose.impersonal(файл, правки)

    assert "2025-11-17 05:11 я: салем\n" in вышло
    assert "я: салем <обращение>" in вышло


