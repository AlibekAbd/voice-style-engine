def test_the_names_in_what_did_not_merge_are_dropped():
    # Глава «Что не свелось» называет собеседника, у которого блок встретился
    # один раз. Для владельца это полезно, для пишущего агента — личные данные
    # живого человека, и обезличиватель их не видит: это не цитата.
    свод = ("### 3. Что не свелось\n\n"
            "- **Спор о продукте** (Пётр Ли (@petr_li)): отстаивает позицию.\n"
            "- **Заказ еды** (Амоня Брат): перечисляет блюда.\n")

    файл = compose.section(свод, {}, людей=8, признаки={})

    assert "@petr_li" not in файл
    assert "Амоня" not in файл
    assert "у одного собеседника" in файл
    assert "отстаивает позицию" in файл


