"""Сборка читаемого файла из свода.

Свод устроен для проверки: в нём перечни «Сведён из», по которым скрипт считает
вес блока и по которым можно вернуться к источнику. Читающему агенту это шум —
он должен видеть определение, примеры и число.
"""

import pytest

from tgservice.voice import compose

СВОД = """### 1. Кто эти собеседники

Кофаундеры и своя команда.

### 2. Блоки речевых действий

### Постановка задач

Сведён из:
- «Задачи» (Цех): ставит задачи прямо
- «Поручения» (Своя команда): поручает работу

Определение: владелец ставит задачи прямо, без смягчения

Примеры:
2025-11-17 05:02 я: Трелло в порядок приведи брат
2026-03-09 08:27 я: 10 постов в Threads

### Религиозные формулы

Сведён из:
- «Дуа» (Родня): пишет молитвы

Определение: владелец пишет исламские формулы

Примеры:
2026-05-26 13:28 я: Алла берекесын берсин

### 3. Что не свелось

- **Спор о продукте** (Проект 2): владелец отстаивает позицию.
"""

ВЕС = {"Постановка задач": {"Цех", "Своя команда"}, "Религиозные формулы": {"Родня"}}


def test_the_merge_sources_do_not_reach_the_file():
    # «Сведён из» нужно, чтобы проверить сведение и посчитать вес. Читающему
    # агенту это шум.
    файл = compose.section(СВОД, ВЕС, людей=8, признаки={})

    assert "Сведён из" not in файл
    assert "(Цех)" not in файл


def test_the_definition_and_the_examples_stay():
    файл = compose.section(СВОД, ВЕС, людей=8, признаки={})

    assert "ставит задачи прямо, без смягчения" in файл
    assert "Трелло в порядок приведи брат" in файл


def test_every_block_carries_its_weight():
    # Черта четырёх человек из пятидесяти пяти — не черта регистра. Без веса
    # файл велел агенту материться там, где владелец не матерился ни разу.
    файл = compose.section(СВОД, ВЕС, людей=8, признаки={})

    assert "у 2 собеседников из 8" in файл
    assert "у 1 собеседника из 8" in файл


def test_a_block_of_a_single_person_is_marked_as_such():
    файл = compose.section(СВОД, ВЕС, людей=8, признаки={})

    место = файл.index("Религиозные формулы")
    assert "у 1 собеседника из 8" in файл[место : место + 400]


def test_what_did_not_merge_survives():
    # Глава по ценности равна основной: в ней исключения.
    файл = compose.section(СВОД, ВЕС, людей=8, признаки={})

    assert "Спор о продукте" in файл


def test_the_counted_traits_are_put_next_to_the_description():
    признаки = {"эмодзи": "3%", "вопросом кончается": "20%", "«вы» против «ты»": "67%"}

    файл = compose.section(СВОД, ВЕС, людей=8, признаки=признаки)

    assert "эмодзи: 3%" in файл
    assert "«вы» против «ты»: 67%" in файл


def test_a_single_person_register_says_nothing_about_weight():
    # У выделенного собеседник один, и «у 1 из 1» не значит ничего.
    файл = compose.section(СВОД, ВЕС, людей=1, признаки={})

    assert "собеседник" not in файл.split("Примеры")[0].split("Определение")[-1]


def test_a_small_share_does_not_round_to_zero():
    # «Исламские формулы 0%» при 0,4% — это приказ никогда их не писать.
    # Округление до целых съедало всё, что реже одного процента.
    assert compose.share(0.004, 1000) == "0,4%"
    assert compose.share(0.0001, 10000) == "меньше 0,1%"
    assert compose.share(0.0, 100) == "не встречается"
    assert compose.share(0.64, 100) == "64%"


def test_a_share_of_nothing_is_not_a_share():
    assert compose.share(0.0, 0) == "нечего считать"


