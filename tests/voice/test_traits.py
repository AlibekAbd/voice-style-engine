"""Измеримые признаки манеры — те, что считает скрипт, а не оценивает агент.

Считаются по выгрузке, а не по раскладке агента: раскладка — его работа, в ней
двух процентов сообщений уже не хватает, и ошибку первого шага унаследовал бы
счёт.

Каждый признак говорит, точен он или приблизителен, и каким правилом получен.
Приблизительное, выданное за точное, вводит в заблуждение сильнее, чем честное
«посчитано вот так, вот что не вошло».
"""

from tgservice.voice import traits, verify


def дамп(text):
    return verify.Batch(text)


# --- длина реплики --------------------------------------------------------


def test_length_is_given_by_spread_and_not_by_one_number():
    # Медиана одна прячет, что владелец пишет и «ок», и восемь строк подряд.
    # Разброс — это и есть манера, а среднее по ней врёт.
    свои = дамп(
        "## 2025-09-24\n"
        "10:00 я: ок\n"
        "10:01 я: да\n"
        "10:02 я: давай завтра созвонимся часов в шесть\n"
    )

    длина = traits.measure(свои)["длина"]

    assert длина["медиана слов"] == 1  # «ок», «да», и одна длинная
    assert длина["корзины"]["1–2"] == 2
    assert длина["корзины"]["6–15"] == 1
    assert длина["точно"] is True


def test_a_multiline_message_is_measured_whole():
    # Продолжение идёт строкой без времени. Меряя первую строку, объявим
    # короткой самую содержательную реплику.
    свои = дамп("## 2025-09-24\n11:21 я: с утра созвонимся\n    с меня контент\n    с тебя код\n")

    assert traits.measure(свои)["длина"]["медиана слов"] == 9  # три строки по три слова


# --- дробление ------------------------------------------------------------


def test_splitting_counts_turns_and_not_messages():
    # Заход — это всё, что владелец написал, пока собеседник молчал. Считая
    # сообщения, получим «дробит всегда» у любого, кто пишет две строки.
    свои = дамп(
        "## 2025-09-24\n"
        "10:00 я: Мана\n"
        "10:00 я: Нурлан\n"
        "10:00 я: в 18:00 подтягивайся\n"
        "10:05 Нурлан Брат: ок\n"
        "10:06 я: ага\n"
    )

    дробление = traits.measure(свои)["дробление"]

    assert дробление["заходов"] == 2
    assert дробление["дроблёных"] == 1
    assert дробление["самая длинная серия"] == 3


def test_every_message_knows_the_size_of_its_turn():
    # Дробление посчитано на регистр, а на вопрос «„че делаешь“ уходит одним
    # сообщением или серией?» файл не отвечал — приходилось лезть в выгрузку.
    # Размер захода у каждого сообщения даёт счёт дробления на блок.
    свои = дамп(
        "## 2025-09-24\n"
        "10:00 я: Мана\n"
        "10:00 я: в 18:00 подтягивайся\n"
        "10:05 Нурлан Брат: ок\n"
        "10:06 я: ага\n"
    )

    размеры = traits.turn_sizes([свои])

    assert размеры[("2025-09-24", "10:00", "Мана")] == {2}
    assert размеры[("2025-09-24", "10:06", "ага")] == {1}
    # Половина цитат собранного файла стоит без времени — таким отвечает ключ
    # по одному дню.
    assert размеры[("2025-09-24", None, "Мана")] == {2}


def test_the_same_words_in_two_chats_keep_both_turn_sizes():
    # Минута и текст не различают чаты: «ок» в одну минуту мог уйти и одиночкой,
    # и серией. Оба размера сохраняются — решать будет счётчик блока, а молчаливый
    # выбор одного из них был бы враньём.
    один = дамп("## 2025-09-24\n10:00 я: ок\n")
    другой = дамп("## 2025-09-24\n10:00 я: ок\n10:00 я: понял, гоу\n")

    размеры = traits.turn_sizes([один, другой])

    assert размеры[("2025-09-24", "10:00", "ок")] == {1, 2}


def test_a_multiline_message_is_found_by_its_first_line():
    # В собранном файле продолжения цитаты отбиты отступом, а в выгрузке лежат
    # одним телом. Ключ по первой строке сводит эти два вида к одному.
    свои = дамп("## 2025-09-24\n11:21 я: с утра созвонимся\n    с меня контент\n")

    размеры = traits.turn_sizes([свои])

    assert размеры[("2025-09-24", "11:21", "с утра созвонимся")] == {1}


# --- эмодзи ---------------------------------------------------------------


def test_bracket_smileys_are_counted_apart_from_emoji():
    # Проверяльщик поймал это на разборе: «в двух случаях он использует
    # скобки-смайлы, но это типографика, а не эмодзи».
    свои = дамп("## 2025-09-24\n10:00 я: спасибо ))\n10:01 я: огонь 🔥\n10:02 я: ок\n")

    эмодзи = traits.measure(свои)["эмодзи"]

    assert эмодзи["с эмодзи"] == 1
    assert эмодзи["со скобками"] == 1


# --- вопрос в конце -------------------------------------------------------


def test_a_question_mark_before_a_trailing_emoji_still_ends_the_message():
    свои = дамп("## 2025-09-24\n10:00 я: ты где ? 😂\n10:01 я: почему? так\n")

    вопрос = traits.measure(свои)["вопрос"]

    assert вопрос["в конце"] == 1
    assert вопрос["внутри"] == 1


# --- язык -----------------------------------------------------------------


def test_the_delay_is_measured_from_the_incoming_message():
    свои = дамп(
        "## 2025-09-24\n"
        "10:00 Санжар Брат: вы в хабе ?\n"
        "10:01 я: да\n"
        "12:00 Санжар Брат: а сейчас\n"
        "15:00 я: подошёл\n"
    )

    задержка = traits.measure(свои)["задержка"]

    assert задержка["медиана минут"] == 90
    assert задержка["в ту же минуту"] == 0


# --- отчёт ----------------------------------------------------------------


def test_the_report_marks_what_is_approximate():
    # Приблизительных признаков в скрипте больше нет: язык и приветствие ушли
    # агенту, потому что список слов — это суждение, выданное за счёт. Но
    # пометка обязана работать, иначе следующий приблизительный пройдёт молча.
    признаки = traits.measure(дамп("## 2025-09-24\n10:00 я: салем\n"))
    признаки["на глаз"] = {"чего-то": 1, "точно": False, "правило": "по списку"}

    отчёт = traits.report(признаки)

    assert "приблизительно" in отчёт
    assert "точно" in отчёт


def test_the_median_is_taken_over_all_messages_and_not_summed():
    один = дамп("## 2025-09-24\n10:00 я: ок\n")
    другой = дамп("## 2025-09-24\n10:00 я: раз два три четыре пять\n")

    всего = traits.total([один, другой])

    assert всего["длина"]["медиана слов"] == 3  # среднее из 1 и 5, а не 6


def test_a_share_is_taken_from_its_own_base():
    # Дроблёных заходов столько-то из заходов, а не из сообщений.
    один = дамп(
        "## 2025-09-24\n10:00 я: раз\n10:00 я: два\n10:05 Санжар Брат: ок\n10:06 я: три\n"
    )

    всего = traits.total([один])

    assert всего["дробление"]["заходов"] == 2
    assert всего["дробление"]["дроблёных"] == 1
    assert всего["дробление"]["из"] == "заходов"


def test_messages_are_the_base_for_what_counts_messages():
    один = дамп("## 2025-09-24\n10:00 я: огонь 🔥\n10:01 я: ок\n")

    всего = traits.total([один])

    assert всего["эмодзи"]["из"] == "сообщений"
    assert всего["сообщений владельца"] == 2

def test_a_delay_across_a_month_border_is_hours_not_days():
    # Минуты считались с месяцем в 31 день: два часа через границу месяца
    # превращались в сутки с лишним и уезжали в «позже суток». Признак при
    # этом стоял с пометкой «точно».
    свои = дамп(
        "## 2026-04-30\n"
        "23:00 Санжар Брат: ты тут?\n"
        "## 2026-05-01\n"
        "01:00 я: тут\n"
    )

    задержка = traits.measure(свои)["задержка"]

    assert задержка["медиана минут"] == 120
    assert задержка["позже суток"] == 0


def test_star_and_clock_emoji_are_emoji():
    # Диапазоны не покрывали ⭐ и ⏰: сообщение с ними считалось «без эмодзи»,
    # а «Ты где? ⭐» терял вопрос в конце — хвостовой знак не отрезался.
    свои = дамп("## 2025-09-24\n10:00 я: круто ⭐\n10:01 я: жду ⏰\n10:02 я: Ты где? ⭐\n")

    признаки = traits.measure(свои)

    assert признаки["эмодзи"]["с эмодзи"] == 3
    assert признаки["вопрос"]["в конце"] == 1


def test_a_bracketed_aside_is_not_a_smiley():
    # «буду позже (наверное)» кончается скобкой, но это скобка, а не смайл:
    # закрывающая уравновешена открывающей.
    свои = дамп(
        "## 2025-09-24\n"
        "10:00 я: буду позже (наверное)\n"
        "10:01 я: спасибо ))\n"
        "10:02 я: ок)\n"
    )

    assert traits.measure(свои)["эмодзи"]["со скобками"] == 2
