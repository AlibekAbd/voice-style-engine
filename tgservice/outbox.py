"""Отправка наружу и её память: чёрный список приманок и журнал отправок.

`say` — единственная дверь из пакета в чужую переписку. Перед отправкой она
сверяет адресата с чёрным списком, после — пишет строку в журнал. Оба файла
читаются и пишутся только функциями этого модуля; пути — `config.BLACKLIST`
и `config.OUTREACH`.

Файл не той формы у любого читателя — `LookupError`, а не пустой список:
сломанная проверка хуже отсутствующей, она отвечает уверенно.
"""
import json
from datetime import datetime, timezone
from pathlib import Path

from telethon.errors import FloodWaitError, PeerFloodError, UnauthorizedError

from . import config, telegram
from .files import read_json, read_lines, write_json


class KnownBot(RuntimeError):
    """Адресат — бот-приманка из чёрного списка. Письмо ему не уходит."""


async def say(app, кому, текст, про="", файл=None):
    """Отправить сообщение. Адресат — юзернейм, а не число.

    Числовые идентификаторы едут после каждой выгрузки, и подстановка
    вчерашних однажды увела шесть чужих чатов с личной перепиской в стороннюю
    модель. Юзернейм не меняется.

    Пустое сообщение — ошибка вызова, а не повод дёргать Телеграм: отправку
    отменить нельзя, и лишний запрос к аккаунту владельца тут ни к чему.

    **Чёрный список приманок сверяется здесь, а не у вызывающего.** 08.09.2026
    два пинга ушли ботам, лежавшим в списке с 02.09: правило «перед любым
    исходящим сверяться» жило в памяти агента, и разовый скрипт проверил не тот
    ключ. Это единственная дверь наружу, поэтому сверка стоит в ней: обойти её
    можно только сознательно. Список не читается — не уходит никто: сломанная
    проверка хуже отсутствующей.

    **Журнал отправок пишется здесь же**, после того как Телеграм принял
    сообщение: время, адресат, дословный текст, номер сообщения. `про` — о
    чём письмо, одной строкой. Строка руками не дублируется.

    **Адресат без юзернейма** — закрытая группа или личка — передаётся как
    `telegram.Чат` из `telegram.чат_по_названию`, а не числом. В журнал он
    пишется как «чат:<название>», а если у него всё же есть юзернейм, сверка
    с чёрным списком идёт по нему, как для всех.

    **Файл** уходит этой же дверью: `файл` — путь на диске, `текст` становится
    подписью к нему и может быть пустым. Сверка с чёрным списком и строка
    журнала те же, что у текста; отсутствующий файл — ошибка вызова до
    обращения к Телеграму.
    """
    if файл is None and not (текст or "").strip():
        raise ValueError("отправлять нечего: текст пуст")
    if файл is not None and not Path(файл).is_file():
        raise FileNotFoundError(f"файла для отправки нет: {файл}")
    if isinstance(кому, telegram.Чат):
        return await _say_to(app, кому.entity, getattr(кому.entity, "username", None) or "",
                             f"чат:{кому.title}", текст, про, файл)
    if str(кому).strip().lstrip("-").isdigit():
        # Правило из докстринга, теперь и в коде: число принималось молча, а
        # защита от повторения дорогого инцидента жила только в прозе.
        raise ValueError(
            f"адресат «{кому}» — число, а отправка идёт только по юзернейму:"
            " числовые идентификаторы едут после каждой выгрузки"
        )
    ник = telegram.username_of(кому)
    return await _say_to(app, кому, ник, ник, текст, про, файл)


async def _say_to(app, адресат, ник, в_журнал, текст, про, файл=None):
    """Сверка с чёрным списком, отправка и строка журнала — общие для всех
    адресатов `say`: и по юзернейму, и чата, найденного по названию."""
    запись = запись_бота(ник)
    if запись:
        raise KnownBot(
            f"адресат «{в_журнал}» — бот-приманка {запись['username']}, в чёрном "
            f"списке с {запись.get('подтверждён', '?')}: {запись.get('чем', '')}"
        )
    try:
        if файл is not None:
            отправлено = await app.send_file(адресат, str(файл), caption=текст)
        else:
            отправлено = await app.send_message(адресат, текст)
    except UnauthorizedError as error:
        raise telegram.SessionGone(telegram.LOGIN_HINT) from error
    except FloodWaitError as error:
        raise telegram.FloodStop(f"Телеграм просит подождать: {error}") from error
    except PeerFloodError as error:
        raise telegram.SpamRestricted(
            "аккаунт ограничен за рассылку — отправка недоступна"
        ) from error
    записать_отправку(в_журнал, текст, про=про,
                      message_id=getattr(отправлено, "id", None))
    return отправлено


def боты_из(путь=None):
    """Ники из чёрного списка приманок.

    **Единственный вход в этот файл.** Разовый парсер, написанный рядом,
    однажды искал ключ «contacts» с полем «contact» — в файле «боты» и
    «username», — вернул «никого нет», и два пинга ушли ботам, лежавшим в
    списке с 02.09. Сломанная проверка хуже отсутствующей: она отвечает
    уверенно.

    Поэтому файл не той формы — поломка, а не пустой список. Отсутствие
    файла пустым списком остаётся: это начало работы.
    """
    return [b["username"] for b in _записи_ботов(путь)]


def запись_бота(ник, путь=None):
    """Запись чёрного списка по нику либо None. Регистр и «собака» не важны."""
    свой = (ник or "").strip().lstrip("@").lower()
    if not свой:
        return None
    for запись in _записи_ботов(путь):
        if запись["username"].lower() == свой:
            return запись
    return None


def бот(ник, путь=None):
    """Этот ник — известная приманка? Регистр и «собака» значения не имеют."""
    return запись_бота(ник, путь) is not None


def _записи_ботов(путь=None):
    """Записи списка целиком. Здесь и живёт проверка формы файла."""
    место = путь or config.BLACKLIST
    if not Path(место).exists():
        return []
    данные = read_json(место, {})
    if "боты" not in данные:
        raise LookupError(
            f"{место}: нет ключа «боты» — формат чёрного списка не тот, "
            "проверка ботов невозможна"
        )
    без_ника = [b for b in данные["боты"] if not b.get("username")]
    if без_ника:
        # Переименованное поле внутри записи давало бы «никого» при полном
        # списке — та же поломка, что и чужой ключ сверху.
        raise LookupError(
            f"{место}: {len(без_ника)} записей без поля «username» — "
            "формат чёрного списка не тот, проверка ботов невозможна"
        )
    return данные["боты"]


def пометить_бота(ник, чем, когда, тексты=(), путь=None):
    """Записать подтверждённую приманку в чёрный список.

    Бот опознаётся по ответу — мгновенной рекламе чужого бота, — и пометка
    ложится сразу же. Иначе следующий круг напишет ему снова, как и вышло
    08.09 с пингами.
    """
    место = Path(путь or config.BLACKLIST)
    данные = read_json(место, {}) if место.exists() else {}
    список = данные.setdefault("боты", [])
    # Проверка «уже есть?» идёт по этому же файлу: `боты_из` знает, что
    # отсутствующий файл пуст. Подстановка боевого пути вместо отсутствующего
    # молча отправляла проверку в другой список.
    if бот(ник, путь=место):
        return список
    список.append({
        "username": (ник or "").strip().lstrip("@"),
        "подтверждён": когда,
        "чем": чем,
        "его_тексты": list(тексты),
    })
    write_json(место, данные)
    return список


def писали_из(путь=None):
    """Кому уже уходило письмо, по журналу отправок.

    Строка журнала без поля «to» — поломка: журнал пишется руками, и
    переименованное поле давало бы «никому не писали» при полном журнале.
    """
    место = путь or config.OUTREACH
    строки = read_lines(место)
    без_адресата = [s for s in строки if not s.get("to")]
    if без_адресата:
        raise LookupError(
            f"{место}: {len(без_адресата)} строк без поля «to» — "
            "формат журнала отправок не тот, проверка «уже писали» невозможна"
        )
    return [s["to"] for s in строки]


def записать_отправку(кому, текст, про="", message_id=None, когда=None, путь=None):
    """Строка журнала отправок: время, адресат, дословный текст, номер сообщения.

    Зовётся из `say` после успешной отправки. Руками строка ставилась
    после каждого письма и однажды забудется — а забытая строка это второе
    письмо тому же человеку. Форма строки та же, что читает `писали_из`.
    """
    место = Path(путь or config.OUTREACH)
    строка = {
        "when": когда or datetime.now(timezone.utc).isoformat(),
        "to": (кому or "").strip().lstrip("@"),
        "about": про or "",
        "text": текст,
        "message_id": str(message_id) if message_id is not None else "",
    }
    место.parent.mkdir(parents=True, exist_ok=True)
    with место.open("a", encoding="utf-8") as f:
        f.write(json.dumps(строка, ensure_ascii=False) + "\n")
    return строка
