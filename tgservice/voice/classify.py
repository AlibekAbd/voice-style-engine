"""Классификация собеседников по типу отношений — ось сведения.

Первый заход резал описания по алфавиту и весу. Группы существовали только
главой внутри свода, и свести по ним было нельзя: в один свод входили чаты из
пяти групп сразу. Отсюда и мат в файле стиля — черта одного человека попала в
общее определение блока, потому что другого места для неё не было.

Здесь класс присваивается **до** всякого сведения, и дальше сводится внутри
класса.

Единица — человек, а не батч. У самого плотного собеседника описание лежит
десятками частей, у редкого — одной: классифицируется собеседник целиком,
иначе получим десятки мнений об одном.

**Выделенные собеседники заданы решением владельца, а не агентом** (`apart`).
Человек, дающий больше половины сообщений, попав в класс, сделает класс своим
портретом.

К моделям этот модуль не ходит.
"""

import hashlib
import re

# Заголовок собеседника в сборном описании. Пишут двумя способами —
# «Собеседник 1:» и «Собеседник 1 из 20:», уровень заголовка гуляет от `#` до
# `####`. Разбирается по факту: требование одного формата уже теряло 27
# описаний из 95.
ЛИЦО = re.compile(
    r"^(?P<уровень>#{1,4})\s*Собеседник\s*\d+(?:\s*из\s*\d+)?\s*:\s*(?P<имя>.+?)\s*$",
    re.M,
)
ПОРТРЕТ = re.compile(
    r"^#{1,5}\s*\d?\.?\s*Кто собеседник[^\n]*\n(?P<текст>.*?)(?=\n#{1,5}\s)", re.M | re.S
)
БЛОКИ_ГЛАВА = re.compile(r"^#{1,5}\s*\d?\.?\s*Блоки речевых действий[^\n]*$", re.M)
# Глава, которой кончаются блоки. Названия блоков повторяются в раскладке, и
# без границы каждый блок посчитается дважды.
ДАЛЬШЕ = re.compile(r"^#{1,5}\s*\d?\.?\s*(Раскладка|Измеримые|Что осталось)", re.M)
ЗАГОЛОВОК = re.compile(r"^#{2,5}\s*(?P<имя>[^\n#][^\n]*?)\s*$", re.M)

# Служебный ключ файла решений: кого сводить своей веткой. Рядом с ним в том
# же файле лежат переименования классов и «__правки к регистрам__».
ОТДЕЛЬНО = "__отдельно__"
# Порог автоматического выделения: доля сообщений владельца от 0 до 1. Кто
# выше — выделяется сам. Значение выбирает владелец; дефолта в коде нет.
ПОРОГ = "__порог__"


def _имя_файла(имя):
    """Имя файла выделенного: без юзернейма, пробелы дефисом, строчными."""
    return re.sub(r"\s+", "-", _ключ(имя).lower()) + ".md"


def apart(решения, карточки=None):
    """Выделенные собеседники: имя → запись из решений владельца.

    Выделенный — тот, кого нельзя сводить с остальными: один человек может
    давать больше половины всех сообщений владельца, и класс, куда он попадёт,
    станет его портретом, а не портретом класса. Такого сводят своей веткой и
    кладут отдельным файлом.

    Кто это — решает владелец файлом, а не код константой: константа делала
    одного человека свойством программы, и на другом владельце программа не
    работала. Два способа, оба в файле решений: поимённо под `ОТДЕЛЬНО` и
    порогом под `ПОРОГ` — тогда по `карточки` считаются доли, и все, кто выше
    порога, выделяются сами. Названный поимённо старше автоматики: его класс и
    файл берутся из записи.

    Поля записи: «класс» (какой класс назначен), «файл» (имя отдельного файла
    в out/voice и в references скилла), «звать» и «кто» (для файла стиля),
    «доля» (необязательно, словами). Без класса человек молча остался бы без
    типа, без файла раскладка молча стёрла бы его файл из скилла — оба
    обязательны.
    """
    from . import compose

    решения = решения or {}
    выделенные = dict(решения.get(ОТДЕЛЬНО, {}))
    for имя, запись in выделенные.items():
        for поле in ("класс", "файл"):
            if not запись.get(поле):
                raise LookupError(f"у выделенного «{имя}» нет поля «{поле}»")
    порог = решения.get(ПОРОГ)
    if порог is None:
        return выделенные
    if isinstance(порог, bool) or not isinstance(порог, (int, float)) or not 0 < порог <= 1:
        raise LookupError(f"порог выделения — доля от 0 до 1, а не {порог!r}")
    if карточки is None:
        # Порог задан, а считать не по чему. Пустой ответ скрыл бы, что
        # автоматика не сработала, и самый плотный ушёл бы агенту.
        raise LookupError("порог выделения задан, а карточек не подано: доли считать не по чему")
    всего = sum(к.get("сообщений", 0) for к in карточки)
    for к in карточки:
        доля = к.get("сообщений", 0) / всего if всего else 0
        if доля >= порог and к["имя"] not in выделенные:
            выделенные[к["имя"]] = {
                "класс": f"{к['имя']} — отдельная категория",
                "файл": _имя_файла(к["имя"]),
                "звать": к["имя"],
                "кто": "Выделен по порогу доли переписки",
                "доля": compose.share(доля, всего),
            }
    return выделенные


def _куски(имя, текст, батч):
    """Части описания по собеседникам: у соло одна, у сборного по каждому."""
    if батч.get("kind") == "solo":
        return [(батч["chats"][0]["name"], текст)]
    места = [(m.start(), m.group("имя")) for m in ЛИЦО.finditer(текст)]
    куски = []
    for номер, (поз, кто) in enumerate(места):
        кон = места[номер + 1][0] if номер + 1 < len(места) else len(текст)
        куски.append((кто, текст[поз:кон]))
    return куски


def _портрет(кусок):
    найдено = ПОРТРЕТ.search(кусок)
    return найдено.group("текст").strip() if найдено else ""


def _блоки(кусок):
    """Названия блоков речевых действий — без тех, что повторены в раскладке."""
    глава = БЛОКИ_ГЛАВА.search(кусок)
    if not глава:
        return []
    хвост = кусок[глава.end() :]
    кон = ДАЛЬШЕ.search(хвост)
    return [m.group("имя").strip() for m in ЗАГОЛОВОК.finditer(хвост[: кон.start() if кон else len(хвост)])]


def cards(описания, индекс, счёт=None):
    """Карточка на каждого собеседника: портрет, блоки и счёт сообщений.

    **Ключ — идентификатор чата, а не имя.** За именем «.» в выгрузке стоят
    четыре разных чата, за «Мадина» — два. Ключ по имени склеивал их в одного
    человека и терял троих.

    Собеседник в сборном описании опознаётся **позицией**: «Собеседник 3 из 20»
    — это третий чат батча, порядок задаёт сам рендер. Имя при этом сверяется с
    индексом, и расхождение записывается в карточку, а не проглатывается.

    Портреты одного человека из разных частей склеиваются: классифицируется
    человек, а не часть переписки.

    Счёт сообщений берётся из `счёт` — он считается по выгрузке. В индексе
    `msgs` стоит на часть, и у собеседника с тридцатью частями вышло бы в разы меньше.
    """
    счёт = счёт or {}
    по_чату = {}
    порядок = []
    for батч in индекс:
        текст = описания.get(батч["file"])
        if текст is None:
            continue
        for место, (кто, кусок) in enumerate(_куски(батч["file"], текст, батч)):
            чат = батч["chats"][место] if место < len(батч["chats"]) else None
            if чат is None:
                continue
            if чат["id"] not in по_чату:
                по_чату[чат["id"]] = {
                    "чат": чат["id"],
                    "имя": кто,
                    "сообщений": счёт.get(чат["id"], 0),
                    "портрет": "",
                    "блоки": [],
                    "батчи": [],
                    "разошлось": None,
                }
                порядок.append(чат["id"])
            карточка = по_чату[чат["id"]]
            if _ключ(кто) != _ключ(чат["name"]) and карточка["разошлось"] is None:
                карточка["разошлось"] = (кто, чат["name"])
            портрет = _портрет(кусок)
            if портрет and портрет not in карточка["портрет"]:
                карточка["портрет"] = (карточка["портрет"] + "\n" + портрет).strip()
            for блок in _блоки(кусок):
                if блок not in карточка["блоки"]:
                    карточка["блоки"].append(блок)
            карточка["батчи"].append(батч["file"])
    return [по_чату[к] for к in порядок]


def _ключ(имя):
    """Имя без юзернейма: в индексе он есть не всегда, в описании — часто."""
    return re.sub(r"\s*\(@[^)]+\)\s*$", "", имя or "").strip()


def sheet(карточки):
    """Лист агенту: пронумерованные карточки.

    Ссылка идёт номером, а не именем. Имя агент перепечатывает руками, а всё
    печатаемое руками портится — на цитатах это стоило четырёх редакций
    задания и так и не вылечилось.
    """
    строки = []
    for номер, к in enumerate(карточки, 1):
        строки.append(f"## {номер}. {к['имя']}")
        строки.append(f"Сообщений владельца: {к['сообщений']}")
        if к["портрет"]:
            строки.append(f"Портрет: {' '.join(к['портрет'].split())}")
        if к["блоки"]:
            строки.append(f"Речевые действия: {', '.join(к['блоки'])}")
        строки.append("")
    return "\n".join(строки)


СТРОКА = re.compile(r"^\s*(?P<номер>\d+)\s*\|(?P<хвост>.+)$", re.M)


def assignments(ответ):
    """Что агент роздал: номер карточки → класс.

    Класс берётся **после последней** черты, а не после второй: чат зовётся
    «Клуб | Поток 2025», и разрез по второй черте отдавал класс
    «Acceleration 2025 | приятель-коллега». Семь таких на корпусе.

    Строка не по формату пропускается, а не угадывается: агент любит вставить
    рассуждение вслух, и разбирать его как ответ — значит завести мусор в
    результат молча.
    """
    роздано = {}
    for m in СТРОКА.finditer(ответ):
        куски = [к.strip() for к in m.group("хвост").split("|")]
        if len(куски) < 2 or not куски[-1]:
            continue
        роздано[int(m.group("номер"))] = куски[-1]
    return роздано


def definitions(ответ, классы=()):
    """Определения типов из хвоста ответа — того, что после строки «# Типы».

    Тип опознаётся по списку розданных классов, а не разрезом по тире: класс
    зовётся «исполнитель (владелец — заказчик)», и разрез по первому тире
    оставлял его без определения.

    Определения нужны проверке: без общего словаря два агента назовут одно
    отношение разными словами, и расхождение выйдет про слова, а не про
    отношения.
    """
    место = re.search(r"^#+\s*Типы\s*$", ответ, re.M)
    if not место:
        return {}
    найдено = {}
    for строка in ответ[место.end():].splitlines():
        строка = строка.strip().lstrip("-*").strip()
        for класс in sorted(классы, key=len, reverse=True):
            if строка.startswith(класс):
                хвост = строка[len(класс):].strip().lstrip("—–-").strip()
                if хвост and класс not in найдено:
                    найдено[класс] = хвост
                break
    return найдено


def integrity(роздано, карточки, типы=None):
    """Целостность ответа: никого не потерял, никого не выдумал.

    Не сошлось — ответ бракуется целиком. Латать классификацию по частям
    нельзя: непонятно, что агент видел, когда её раздавал.

    Тип без определения — тоже поломка: проверять его будет нечем.
    """
    ждём = set(range(1, len(карточки) + 1))
    есть = set(роздано)
    не_роздано = sorted(ждём - есть)
    лишние = sorted(есть - ждём)
    # `if типы` отключало проверку ровно тогда, когда сломано всё: агент не
    # написал раздел типов вовсе, словарь пуст — и «без определения» молчал.
    # Пустой словарь — самый тяжёлый случай этой поломки.
    без_определения = (
        sorted(set(роздано.values()) - set(типы)) if типы is not None else []
    )
    return {
        "цело": not не_роздано and not лишние and not без_определения,
        "не роздано": не_роздано,
        "лишние": лишние,
        "классов": len(set(роздано.values())),
        "размеры": _размеры(роздано),
        "без определения": без_определения,
    }


def _размеры(роздано):
    счёт = {}
    for класс in роздано.values():
        счёт[класс] = счёт.get(класс, 0) + 1
    return dict(sorted(счёт.items(), key=lambda пара: -пара[1]))


def sample(роздано, сколько=5):
    """По нескольку человек из каждого класса — на проверку по сырой речи.

    Выбор считается от номера, а не жребием: замер обязан повторяться, иначе
    в результат входит везение.
    """
    по_классам = {}
    for номер, класс in sorted(роздано.items()):
        по_классам.setdefault(класс, []).append(номер)
    выборка = {}
    for класс, номера in по_классам.items():
        порядок = sorted(номера, key=lambda n: hashlib.sha256(f"{класс}-{n}".encode()).hexdigest())
        выборка[класс] = sorted(порядок[:сколько])
    return выборка


def excerpt(сообщения, кто, сколько=30):
    """Отрывок переписки для проверки по сырой речи.

    Обе стороны: по одной отношения не видны — «Норм» ничего не говорит без
    «Как дела».

    Берётся из середины. Начало переписки — это знакомство, и оно у всех
    похоже: представился, объяснил, откуда контакт. Отношения видны там, где
    они уже сложились.
    """
    живые = [m for m in сообщения if (m.get("text") or "").strip()]
    if len(живые) > сколько:
        начало = (len(живые) - сколько) // 2
        живые = живые[начало : начало + сколько]
    return "\n".join(
        f"{m['date'][11:16]} {'я' if m.get('out') else кто}: {' '.join(m['text'].split())}"
        for m in живые
    )


def rename(роздано, типы, решения):
    """Переименования классов по решению владельца.

    Правка руками теряется на первой же пересборке. Решение лежит файлом и
    применяется скриптом — как класс выделенного собеседника.

    Решение про класс, которого никто не носит, — это опечатка, и молчать о
    ней нельзя: переименование просто не случится, а выглядеть будет как
    случившееся.
    """
    # Служебные ключи вида «__правки к регистрам__» — не классы: их читает
    # сборка файла стиля, а не переименование.
    классы = {имя for имя in решения if not имя.startswith("__")}
    чужие = sorted(классы - set(типы) - set(роздано.values()))
    if чужие:
        raise LookupError(f"переименовать нечего, таких классов нет: {', '.join(чужие)}")
    новое = {
        имя: решения.get(класс, {}).get("звать", класс) for имя, класс in роздано.items()
    }
    новые_типы = {}
    for класс, определение in типы.items():
        решение = решения.get(класс, {})
        новые_типы[решение.get("звать", класс)] = решение.get("определение", определение)
    return новое, новые_типы


def registers(роздано, карта):
    """Класс → регистр общения. Ось, по которой собирается файл стиля.

    Восемнадцать классов — это справочник людей, а он в работе не нужен:
    агент, отвечая на письмо, читает саму переписку и узнаёт по ней, как
    говорить. Различать «знакомого» от «партнёра» по тридцати сообщениям
    нельзя, и требовать этого значит закладывать ошибку.

    Укрупнение проверено на восьмидесяти вердиктах судьи: восемнадцать классов
    дали 65% попадания, четыре регистра — 82% на тех же ответах.

    Класс без регистра — это люди, молча выпавшие из свода. Их надо назвать.
    """
    чужие = sorted(set(роздано.values()) - set(карта))
    if чужие:
        raise LookupError(f"классы без регистра: {', '.join(чужие)}")
    return {имя: карта[класс] for имя, класс in роздано.items()}


def portions(куски, регистр, потолок=200_000):
    """Куски описаний одного регистра, разложенные по порциям агенту свода.

    Единица нарезки — человек. Части одного собеседника не разлучаются: у
    самого плотного собеседника десятки частей, и разложив их по разным
    порциям, получим десятки сводов об одном человеке и ни одного о нём целиком.

    Человек тяжелее потолка идёт своими порциями и своим уровнем свода. Один
    человек может давать три четверти регистра: смешав его с прочими, получим свод о нём,
    названный сводом о группе. Ровно так мат одного чата стал чертой всех
    близких.
    """
    from .common import tokens

    свои = {}
    порядок = []
    for кто, чей, текст in куски:
        if чей != регистр:
            continue
        if кто not in свои:
            свои[кто] = []
            порядок.append(кто)
        свои[кто].append((кто, текст))

    готовые, текущая, набрано = [], [], 0
    for кто in порядок:
        части = свои[кто]
        весит = sum(tokens(текст) for _, текст in части)
        if весит > потолок:
            if текущая:
                готовые.append(текущая)
                текущая, набрано = [], 0
            своё = []
            для_себя = 0
            for часть in части:
                вес = tokens(часть[1])
                if своё and для_себя + вес > потолок:
                    готовые.append(своё)
                    своё, для_себя = [], 0
                своё.append(часть)
                для_себя += вес
            if своё:
                готовые.append(своё)
            continue
        if текущая and набрано + весит > потолок:
            готовые.append(текущая)
            текущая, набрано = [], 0
        текущая.extend(части)
        набрано += весит
    if текущая:
        готовые.append(текущая)
    return готовые


ИСТОЧНИК = re.compile(r"^-\s*«(?P<блок>[^»]+)»\s*\((?P<чей>[^)]+)\)", re.M)
# Ссылку на нижний свод агенты пишут тремя способами: «свод «низ-1»», «свод
# низ-1» и просто «низ-1» (последнее ловится проверкой по списку низовых).
# Без формы без ёлочек свод превращался в человека, и вес блока выходил
# единицей вместо десятков — молча.
СВОД_В_СКОБКАХ = re.compile(r"^свод\s*«?(?P<имя>[^»]+?)»?$")


def _блоки_свода(текст):
    """Блоки свода: название → перечень источников из «Сведён из»."""
    найдено = {}
    for кусок in re.split(r"\n#{3}\s+", "\n" + текст)[1:]:
        имя = кусок.split("\n")[0].strip()
        найдено[имя] = [
            (m.group("блок").strip(), m.group("чей").strip())
            for m in ИСТОЧНИК.finditer(кусок)
        ]
    return найдено


def weights(свод, ниже):
    """У скольких собеседников встретился каждый блок. Считает скрипт.

    Верхний свод перечисляет в источниках нижние своды, а не людей, и вес
    собеседников на верхнем уровне терялся: у «приятельского» вышло по
    одному-двум источникам на блок вместо десятков, у «формального» — триста
    тридцать пять. Один и тот же промпт, разное поведение — значит на агента
    в этом полагаться нельзя.

    Счёт идёт по цепочке: блок верхнего свода называет блоки нижних, блок
    нижнего называет собеседников.
    """
    низовые = {имя: _блоки_свода(текст) for имя, текст in ниже.items()}
    итог = {}
    for блок, источники in _блоки_свода(свод).items():
        кто = set()
        for имя_блока, чей in источники:
            голое = чей
            свод_ниже = СВОД_В_СКОБКАХ.match(чей)
            if свод_ниже:
                голое = свод_ниже.group("имя")
            if голое in низовые:
                for _, человек in низовые[голое].get(имя_блока, []):
                    кто.add(человек)
            else:
                for один in re.split(r"\s*[,;]\s*", чей):
                    if один.strip():
                        кто.add(один.strip())
        итог[блок] = кто
    return итог
