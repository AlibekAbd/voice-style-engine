"""Сборка читаемого раздела файла стиля из свода.

Свод устроен для проверки: перечни «Сведён из» держат связь с источником и по
ним скрипт считает вес блока. Читающему агенту это шум — ему нужно определение,
примеры и число.

**Вес обязателен у каждого блока.** Без него черта четырёх человек из пятидесяти
пяти читается как черта регистра: файл велел агенту материться там, где владелец
не матерился ни разу. Мата в корпусе 0,4% сообщений, и 70% из них в одном чате.

К моделям не ходит.
"""

import re

ЗАГОЛОВОК = re.compile(r"^(?P<решётки>#{2,4})\s*(?P<имя>.+?)\s*$", re.M)
СВЕДЁН = re.compile(r"^Сведён из:\s*$", re.M)
# Маркер перечня гуляет: «-» и «*». Строка источника с «*» не срезалась и
# утекала в файл стиля вместе с именем собеседника — мимо обезличивателя.
ИСТОЧНИК = re.compile(r"^[-*]\s*«[^»]+»\s*\([^)]*\)\s*:?.*$", re.M)
ГЛАВА = re.compile(r"^#{1,4}\s*\d+\.\s", re.M)
# Строка главы «Что не свелось»: блок, встретившийся у одного собеседника, и
# его имя в скобках. Имя — личные данные живого человека, и обезличиватель его
# не видит: это не цитата, а проза.
ОДИНОЧКА = re.compile(r"^(?P<начало>[-*]\s*\*\*[^*]+\*\*)\s*\((?P<кто>[^)]*(?:\([^)]*\))?[^)]*)\)\s*:", re.M)
# Служебные строки порции: с них начинается лист, который уходил агенту. Агент
# их иногда перепечатывает в ответ, и они затекают в готовый файл.
СЛУЖЕБНОЕ = re.compile(r"^#{1,4}\s*(Регистр:|Описание переписки:|Описание батча)", re.M)


def _склонение(сколько):
    """«1 собеседника», «2 собеседников» — иначе читается как опечатка."""
    if сколько % 10 == 1 and сколько % 100 != 11:
        return "собеседника"
    return "собеседников"


def section(свод, вес, людей, признаки):
    """Раздел файла из свода одного регистра.

    Убирается «Сведён из» с перечнем источников. Взамен под определением
    встаёт вес: у скольких собеседников регистра блок встретился.

    При одном собеседнике вес не пишется: «у 1 из 1» не значит ничего.

    Блок без веса — отказ, а не пропуск строки: имя блока, разошедшееся с
    ключом веса, публиковало бы блок без веса молча, и черта одного человека
    читалась бы как черта регистра — ровно история с матом, ради которой вес
    и введён.
    """
    строки, внутри = [], False
    for line in свод.splitlines():
        if СВЕДЁН.match(line):
            внутри = True
            continue
        if внутри:
            if ИСТОЧНИК.match(line) or not line.strip():
                continue
            внутри = False
        if СЛУЖЕБНОЕ.match(line):
            continue
        заголовок = ЗАГОЛОВОК.match(line)
        строки.append(line)
        if заголовок and not ГЛАВА.match(line) and людей > 1:
            имя = заголовок.group("имя")
            свои = вес.get(имя)
            if not свои:
                raise LookupError(
                    f"у блока «{имя}» нет веса: имя разошлось с «Сведён из» или цепочка порвана"
                )
            строки.append("")
            строки.append(f"Встречается у {len(свои)} {_склонение(len(свои))} из {людей}.")
    собрано = ОДИНОЧКА.sub(r"\g<начало> (у одного собеседника):", "\n".join(строки))
    собрано = re.sub(r"\n{3,}", "\n\n", собрано).strip()
    return собрано + _числа(признаки)


def _числа(признаки):
    """Посчитанное скриптом — рядом с описанием, а не вместо него."""
    if not признаки:
        return "\n"
    строки = ["", "", "### Что посчитано по этому регистру", ""]
    строки += [f"- {имя}: {значение}" for имя, значение in признаки.items()]
    return "\n".join(строки) + "\n"


# Цитата блока: дата, необязательное время, «я:». Половина цитат собранного
# файла стоит без времени, а в одном из отдельных файлов все до единой обрамлены обратными
# кавычками — формат читается по факту.
ЦИТАТА = re.compile(
    r"^`?(?P<день>\d{4}-\d{2}-\d{2})(?:\s+(?P<время>\d{2}:\d{2}))?\s+я:\s?(?P<текст>.*?)`?\s*$"
)
ВЕС = re.compile(r"^Встречается у \d+ собеседник(а|ов) из \d+\.$")
ДРОБЛЕНИЕ = re.compile(r"^Дробление примеров по выгрузке: .*$\n?", re.M)


def _счёт_дробления(цитаты, размеры):
    """Одиночных, серий, нерешённых — по размерам заходов из выгрузки.

    Не решилось — цитата, которой в выгрузке нет (обезличена или обрезана),
    и цитата, чей текст в одну минуту уходил и одиночкой, и серией. Молча
    выкинув такие, счёт выглядел бы полным.
    """
    одиночных = серий = нерешённых = 0
    for день, время, текст in цитаты:
        свои = размеры.get((день, время, текст.strip()), set())
        if свои == {1}:
            одиночных += 1
        elif свои and 1 not in свои:
            серий += 1
        else:
            нерешённых += 1
    return одиночных, серий, нерешённых


def splitting(файл, размеры):
    """Строка дробления у каждого блока: по цитатам самого блока.

    Дробление на регистр («61% заходов дроблены») не говорит, как уходит
    конкретный оборот. Ответ лежит в выгрузке: у цитат блока есть отметки,
    по ним виден размер захода.

    Строка встаёт рядом с весом блока — это его числа. Старый счёт снимается,
    а не наслаивается: пересчёт по свежей выгрузке ложится на его место.
    Блок, где не решилась ни одна цитата, строки не получает — «0 и 0» под
    каждым блоком был бы шумом.
    """
    строки = ДРОБЛЕНИЕ.sub("", файл).splitlines()
    границы = [номер for номер, line in enumerate(строки) if line.startswith("### ")]
    for номер, начало in reversed(list(enumerate(границы))):
        конец = границы[номер + 1] if номер + 1 < len(границы) else len(строки)
        цитаты = [
            (found["день"], found["время"], found["текст"])
            for line in строки[начало:конец]
            if (found := ЦИТАТА.match(line))
        ]
        одиночных, серий, нерешённых = _счёт_дробления(цитаты, размеры)
        if not (одиночных or серий):
            continue
        хвост = f", не решилось {нерешённых}." if нерешённых else "."
        строка = f"Дробление примеров по выгрузке: одним сообщением {одиночных}, серией {серий}{хвост}"
        весы = [
            место for место in range(начало, конец)
            if ВЕС.match(строки[место])
        ]
        if весы:
            строки.insert(весы[0] + 1, строка)
        else:
            строки[начало + 1:начало + 1] = ["", строка]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(строки))


def leaked(файл, имена):
    """Имена собеседников, найденные в готовом файле словом.

    Обезличиватель чистит цитаты, а имя в прозе держится на одном хрупком
    формате одиночного блока. Это страховка после сборки: список известных
    имён прогоняется по файлу до того, как тот уедет в скилл. Имя ищется
    словом, а не подстрокой — «Али» внутри «сказали» не утечка.
    """
    найдены = []
    for имя in имена:
        # Хвост до трёх букв — падеж: «У Рината», «с Алией». Начало строгое:
        # имя не начинается посреди слова.
        if re.search(rf"(?<!\w){re.escape(имя)}\w{{0,3}}(?!\w)", файл):
            найдены.append(имя)
    return найдены


def share(доля, из_скольких):
    """Доля словами. Округление до целых съедало всё, что реже процента.

    «Исламские формулы 0%» при настоящих 0,4% — это не округление, а приказ
    агенту никогда их не писать. Малые доли пишутся десятыми, а совсем
    редкое — словами, чтобы не выдавать единичный случай за долю.
    """
    if not из_скольких:
        return "нечего считать"
    if доля <= 0:
        return "не встречается"
    if доля < 0.001:
        return "меньше 0,1%"
    if доля < 0.01:
        return f"{доля * 100:.1f}%".replace(".", ",")
    return f"{доля * 100:.0f}%"


# Числа корпуса были зашиты в текст: пересборка по
# свежей выгрузке собирала файл со старыми числами в первой же строке.
# Числа приезжают из замера параметром `корпус`; без него строка идёт без чисел.
ШАПКА = """# Как владелец переписки пишет сообщения

Файл снят с его настоящей переписки за год{снято}. Читается перед тем, как
написать сообщение от его имени.

## Как этим пользоваться

**Шаг первый — узнай регистр.** Посмотри переписку с этим человеком: на «ты»
он или на «вы», здоровается ли, как обращается, о чём речь. Регистров четыре,
признаки для их различения — в таблице ниже.

**Шаг второй — возьми раздел этого регистра** и пиши по нему.

Узнавание — самое слабое место: на отрывке в тридцать сообщений оно даёт около
82% попаданий. Если переписки мало или она не похожа ни на что, бери
«приятельское деловое» — он самый большой и самый средний.

## Что верно во всех регистрах

Это привычка руки, она не зависит от собеседника."""

# Абзац про выделенного собеседника: кто он и почему его нет в общем файле.
# Имя, роль и доля приезжают из решений владельца (`classify.apart`), а не
# из текста программы: имя в коде делало одного человека свойством программы.
ОТДЕЛЬНЫЙ = """**{звать}.** {кто}{доля}. Его манера описана отдельным файлом: сведи его
с остальными — и портрет одного человека станет портретом всех.

"""

ХВОСТ = """## Чего в этом файле нет

{отдельные}**Смысла сообщений.** Файл говорит, **как** владелец пишет, и не говорит,
**что** писать. Содержание берётся из задачи, а не отсюда.

**Точных частот оборотов.** «Встречается у 12 собеседников из 55» — это у
скольких людей оборот вообще замечен, а не как часто он звучит. Человек может
писать «брат» через слово, и он всё равно посчитан один раз."""


# Ключ правок владельца в файле решений — рядом с переименованиями классов.
ПРАВКИ = "__правки к регистрам__"


def amendments(решения):
    """Раздел решений владельца из файла решений.

    Вклеивает скрипт, а не рука: правка руками теряется на первой же
    пересборке. Расхождение с корпусом названо в самой правке, чтобы её не
    «починили» обратно по измерению.
    """
    строки = [
        "## Решения владельца",
        "",
        "Правки «как надо» поверх измеренного «как есть». Где правка расходится",
        "с корпусом, расхождение названо в ней самой — оно не ошибка сборки.",
    ]
    for имя, поля in решения.items():
        строки += ["", f"### К регистру «{имя}»", "", поля["правка"]]
        for ключ, текст in поля.items():
            if ключ != "правка":
                строки += ["", f"**{ключ.capitalize()}.** {текст}"]
    return "\n".join(строки)


def book(общее, узнавание, разделы, решения=None, корпус=None, отдельно=None):
    """Файл стиля целиком: общее наверху, узнавание таблицей, разделы по одному.

    Общие привычки стоят один раз. Медиана длины и дробление одинаковы во всех
    регистрах — повторив их четырежды, внушим читающему агенту, что они зависят
    от собеседника.

    Решения владельца встают до первого регистра: раскладка по скиллу режет
    от «### Регистр:», и в порождаемые файлы регистров решения не попадают.
    Правка к регистру, которого нет, останавливает сборку — молча пропущенная,
    она выглядела бы применённой.

    Выделенные собеседники (`отдельно` — список записей с полями «звать»,
    «кто», «доля») названы в хвосте по одному абзацу: их манера лежит
    отдельными файлами, и читающий агент должен знать, кого в этом файле нет.
    """
    корпус = корпус or {}
    снято = (
        f": {корпус['собеседников']} собеседников, {корпус['сообщений']} его сообщений"
        if корпус.get("собеседников")
        else ""
    )
    строки = [ШАПКА.format(снято=снято), ""]
    строки += [f"- {имя}: {значение}" for имя, значение in общее.items()]
    if узнавание:
        строки += ["", "## Четыре регистра и как их узнать", ""]
        столбцы = list(узнавание[0])
        строки.append("| " + " | ".join(столбцы) + " |")
        строки.append("|" + "---|" * len(столбцы))
        for ряд in узнавание:
            строки.append("| " + " | ".join(str(ряд.get(с, "")) for с in столбцы) + " |")
    if решения:
        чужие = sorted(set(решения) - {имя for имя, _ in разделы})
        if чужие:
            raise LookupError(f"правка к регистру, которого нет: {', '.join(чужие)}")
        строки += ["", amendments(решения)]
    for имя, текст in разделы:
        строки += ["", "---", "", f"### Регистр: {имя}", "", текст.strip()]
    абзацы = "".join(
        ОТДЕЛЬНЫЙ.format(
            звать=з["звать"], кто=з["кто"],
            доля=f", {з['доля']} всей переписки" if з.get("доля") else "",
        )
        for з in (отдельно or [])
    )
    строки += ["", "---", "", ХВОСТ.format(отдельные=абзацы)]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(строки)).strip() + "\n"


# --- обезличивание --------------------------------------------------------
#
# Восстановлено из 9499ea9 вместе с тремя починками, за которые заплачено
# отладкой: подача цитаты целиком, многострочное «БЫЛО», терпимость вклейки к
# невидимому хвостовому пробелу и счёт по факту замены.

# Цитата с продолжением: первая строка с отметкой, дальше строки с отступом.
# Цитата бывает обрамлена обратными кавычками: агент одного из сводов обрамил так
# все до единой, и разбор не увидел ни одной — файл ушёл на обезличивание с
# нулём цитат. Формат читается по факту, а не по задуманному.
# Время необязательно, как в ЦИТАТА: девять цитат файла стиля стоят без
# времени, и обезличивающий агент их не видел вовсе.
QUOTE_HEAD = re.compile(r"^\s*`?\d{4}-\d{2}-\d{2}(?:\s+\d{2}:\d{2})?\s+я:")


def quotes(файл):
    """Цитаты файла целиком — с продолжениями, а не только первой строкой.

    Телефон гастроэнтеролога стоял второй строкой и агенту не показывался:
    отбирались только строки с отметкой времени. Дыру потом латали регуляркой,
    хотя чинить надо было подачу.

    Личные данные вычищает агент, а не образец. Образец неполон по устройству:
    ловит «+7 701...» и пропускает то же самое, написанное иначе, — ровно как
    список казахских слов, который дал 0,03% вместо 1,7%.
    """
    найдено, текущая = [], None
    for line in файл.splitlines():
        if QUOTE_HEAD.match(line):
            if текущая:
                найдено.append("\n".join(текущая))
            текущая = [line.strip().strip("`")]
        elif текущая is not None and line.startswith((" ", "\t")) and line.strip():
            текущая.append(line.rstrip())
        elif текущая:
            найдено.append("\n".join(текущая))
            текущая = None
    if текущая:
        найдено.append("\n".join(текущая))
    return найдено



PATCH_LINE = re.compile(r"^\s*(?P<mark>БЫЛО|СТАЛО):\s?(?P<text>.*)$")


def replacements(заплатка):
    """Пары «было — стало» из ответа агента-обезличивателя.

    Многострочна обе стороны. Цитату агенту подают целиком, и «БЫЛО» он
    присылает целиком же — а читалось только до первого перевода строки.
    Телефон второй строкой агент находил, вклеить правку было нечем:
    «обезличено 0 из 3».

    Отступ продолжения сохраняется дословно: по «БЫЛО» ищется место в файле, а
    там продолжение отбито пробелами.
    """
    правки, было, стало, сторона = {}, None, [], None
    for line in заплатка.splitlines():
        found = PATCH_LINE.match(line)
        if found and found.group("mark") == "БЫЛО":
            if было is not None:
                правки["\n".join(было)] = "\n".join(стало)
            было, стало, сторона = [found.group("text").rstrip()], [], было
            сторона = "было"
        elif found:
            стало.append(found.group("text").rstrip())
            сторона = "стало"
        elif сторона and line.strip():
            # Продолжение многострочной цитаты идёт строкой без пометки.
            (было if сторона == "было" else стало).append(line.rstrip())
    if было is not None:
        правки["\n".join(было)] = "\n".join(стало)
    return правки


def impersonal(файл, правки, счёт=False):
    """Подставить обезличенное вместо исходного.

    Ищется по тексту цитаты, а не по строке файла целиком: агент присылает
    «БЫЛО» без отметки времени — он видит цитату, а не строку. Требуя строку
    целиком, не вклеили ни одной из двадцати двух правок.

    Краевые пробелы строки в счёт не идут. В выгрузке текст лежит дословно, и
    владелец нередко заканчивает строку пробелом; воспроизвести невидимый
    пробел агент не может. Требуя строку дословно, не вклеили ни одной правки,
    а счётчик отчитался «26 из 26»: он смотрел, находится ли «БЫЛО» в файле
    после правки, а не легло ли «СТАЛО».

    С `счёт=True` возвращает пару: файл и список вклеенного.
    """
    строки, легло = файл.splitlines(keepends=True), []
    for было, стало in правки.items():
        if not было:
            continue
        искомое = [one.rstrip() for one in было.splitlines()]
        место = _place(строки, искомое)
        if место is None:
            continue
        новые = стало.splitlines()
        # Отметка времени стоит перед цитатой в той же строке, и агент её не
        # видел: первую строку правим вхождением, остальные заменяем целиком.
        первая = строки[место].rstrip().replace(искомое[0], новые[0], 1)
        конец = "\n" if строки[место + len(искомое) - 1].endswith("\n") else ""
        строки[место : место + len(искомое)] = [
            one + "\n" for one in [первая] + новые[1:-1]
        ] + ([новые[-1] + конец] if len(новые) > 1 else [])
        if len(новые) == 1:
            строки[место] = первая + конец
        легло.append(было)
    собрано = "".join(строки)
    return (собрано, легло) if счёт else собрано


def _place(строки, искомое):
    """Где в файле лежит цитата: номер первой её строки или `None`.

    Первая строка цитаты стоит в файле за отметкой времени, остальные — сами
    по себе, потому сравниваются по-разному: первая вхождением, прочие целиком.
    """
    for начало in range(len(строки) - len(искомое) + 1):
        куски = [one.rstrip() for one in строки[начало : начало + len(искомое)]]
        if искомое[0] in куски[0] and куски[1:] == искомое[1:]:
            return начало
    return None
