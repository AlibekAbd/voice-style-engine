"""Раскладка собранного файла стиля по файлам скилла.

Скилл живёт двумя руками, и это главное, что здесь устроено.

**Файлы регистров порождаются.** Они целиком повторяют то, что сведено из
переписки, и переписываются при каждой пересборке свода. Править их руками
бессмысленно: правка исчезнет на следующем прогоне.

**SKILL.md, журнал замечаний и выведенные из них правила пишутся руками.**
Скрипт их не трогает никогда. Это решения владельца «как надо», а файлы
регистров — измеренное «как есть»; смешав их в одном файле, потеряем и то и
другое.

Числа из таблицы узнавания стоят в SKILL.md, который скрипт не переписывает.
Поэтому `stale` называет расхождение вслух — прикрывать дыру цифрой, которой
нельзя верить, здесь уже приходилось.
"""

import re
from pathlib import Path

from .. import config
from . import classify, compose
from .common import CARDS, DECISIONS, VOICE, read_json

STYLE = VOICE / "стиль.md"
SKILL = config.CODE_DIR.parent / "Skills for Telegram" / "tg-voice"

# Что лежит в references и при этом написано руками. Раскладка убирает из
# references всё, чего нет в своде, и этот список — единственное исключение.
РУКОЙ = {"правила.md"}

# Хвост заголовка обрезается пробелами, а не `\s`: `\s*$` съедал перевод строки
# вместе с пустой строкой под ним, и заголовок регистра слипался с первой главой.
РЕГИСТР = re.compile(r"^### Регистр:[ \t]*(?P<имя>.+?)[ \t]*$", re.M)
СТРОКА = re.compile(r"^\|\s*(?P<имя>[^|]+?)\s*\|(?P<хвост>.+)\|\s*$", re.M)
# Дробь с запятой — тоже число: «0,4%» выпадало из сверки молча.
ЧИСЛО = re.compile(r"^[\d\s]+(?:,\d+)?%?$")
ХВОСТ = "\n## Чего в этом файле нет"


def _подрезать(кусок):
    """Снимает разделители и пустоту с конца раздела."""
    строки = кусок.rstrip().splitlines()
    while строки and строки[-1].strip() in {"", "---"}:
        строки.pop()
    return "\n".join(строки) + "\n"


def _имя_файла(регистр):
    return регистр.replace(" ", "-") + ".md"


def split(файл):
    """Режет собранный файл на разделы регистров.

    Общая шапка и хвост «Чего в этом файле нет» за борт: они живут в SKILL.md.
    Разъехавшись по четырём файлам, они разойдутся и между собой.
    """
    край = файл.find(ХВОСТ)
    тело = файл if край < 0 else файл[:край]
    метки = list(РЕГИСТР.finditer(тело))
    разделы = {}
    for номер, метка in enumerate(метки):
        конец = метки[номер + 1].start() if номер + 1 < len(метки) else len(тело)
        кусок = тело[метка.start():конец]
        # Регистр стоял третьим уровнем под общей шапкой. Отдельным файлом он
        # сам себе заголовок, иначе главы внутри окажутся выше него.
        кусок = "# Регистр: " + метка.group("имя") + кусок[метка.end() - метка.start():]
        разделы[метка.group("имя")] = _подрезать(кусок)
    return разделы


def numbers(текст, имена=None):
    """Числа таблицы узнавания: по регистру — людей, «вы», вопросом, эмодзи.

    Берутся только ячейки, целиком состоящие из числа. Заголовок таблицы и
    строка разделителя отсеиваются этим же условием, без счёта столбцов:
    столбец добавят, и счёт молча съедет.
    """
    найдено = {}
    for строка in СТРОКА.finditer(текст):
        имя = строка.group("имя")
        if имена is not None and имя not in имена:
            continue
        ячейки = [кусок.strip() for кусок in строка.group("хвост").split("|")]
        числа = [кусок for кусок in ячейки if ЧИСЛО.match(кусок)]
        if числа:
            найдено[имя] = числа
    return найдено


def stale(скилл, свод):
    """Регистры, у которых числа в SKILL.md разошлись со сводом.

    Пропавшая строка считается расхождением наравне с изменившимся числом:
    регистр, о котором SKILL.md молчит, агент не узнает. И обратная сторона:
    строка таблицы про регистр, выбывший из свода, — надгробие с числами,
    которым нельзя верить, и её тоже надо назвать.
    """
    источник = numbers(свод)
    в_скилле = numbers(скилл)
    пропало = [имя for имя, числа in источник.items() if в_скилле.get(имя) != числа]
    лишние = [имя for имя in в_скилле if имя not in источник]
    return пропало + лишние


def write(куда, файл, отдельные=None, беречь=()):
    """Кладёт разделы регистров и файлы выделенных в references, лишнее убирает.

    Цель опознаётся по SKILL.md до первой записи: раскладка удаляет из
    references всё, чего нет в своде, и промах папкой стёр бы чужое.

    Пустой разрез — отказ, а не пустой свод: это съехавший формат заголовков,
    и раскладка по нему снесла бы все файлы регистров молча, вернув
    «написано: нурлан.md» без единой ошибки.

    `отдельные` — имя файла → текст, файлы выделенных собеседников. `беречь` —
    имена файлов, которые не трогать, даже если их нет среди написанного:
    файл выделенного, отсутствующий на диске в этот раз, — это не «человек
    выбыл», и стирать его из references нельзя.
    """
    куда = Path(куда)
    if not (куда / "SKILL.md").exists():
        raise ValueError(f"не похоже на скилл: нет SKILL.md в {куда}")

    разделы = split(файл)
    if not разделы:
        raise ValueError(
            "в своде не нашлось ни одного «### Регистр:» — формат съехал,"
            " раскладка отменена, файлы регистров не тронуты"
        )

    references = куда / "references"
    references.mkdir(parents=True, exist_ok=True)

    готово = {_имя_файла(имя): текст for имя, текст in разделы.items()}
    for имя, текст in (отдельные or {}).items():
        готово[имя] = текст.rstrip() + "\n"

    написано = []
    for имя, текст in готово.items():
        путь = references / имя
        путь.write_text(текст, encoding="utf-8")
        написано.append(путь)

    неприкосновенно = РУКОЙ | set(беречь) | set(готово)
    for путь in sorted(references.glob("*.md")):
        if путь.name not in неприкосновенно:
            путь.unlink()

    return написано


def undecided(файл, решения):
    """Регистры, чья правка владельца в собранный файл не легла.

    Пересборка, забывшая подать решения, выглядит случившейся: файл собран,
    регистры на месте. Поэтому пропажа называется вслух — как у `stale`.
    """
    return [имя for имя, поля in решения.items() if поля["правка"] not in файл]


def pack(куда=None):
    """Раскладывает готовый свод по скиллу и называет расхождения.

    Выделенных собеседников берёт из решений владельца: их файлы кладутся
    рядом с регистрами, а названные в решениях, но не лежащие на диске,
    остаются в references нетронутыми.

    Возвращает тройку: что написано, чьи числа узнавания в SKILL.md устарели,
    чья правка владельца в свод не вклеена.
    """
    цель = Path(куда) if куда else SKILL
    файл = STYLE.read_text(encoding="utf-8")
    решения = read_json(DECISIONS, {})
    # Карточки нужны только порогу; без порога их отсутствие ничего не значит.
    выделенные = classify.apart(решения, read_json(CARDS))
    отдельные = {}
    for запись in выделенные.values():
        место = VOICE / запись["файл"]
        if место.exists():
            отдельные[запись["файл"]] = место.read_text(encoding="utf-8")
    беречь = {запись["файл"] for запись in выделенные.values()}
    написано = write(цель, файл, отдельные, беречь=беречь)
    разошлись = stale((цель / "SKILL.md").read_text(encoding="utf-8"), файл)
    без_правок = undecided(файл, решения.get(compose.ПРАВКИ, {}))
    return написано, разошлись, без_правок
