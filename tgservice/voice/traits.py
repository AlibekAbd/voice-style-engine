"""Измеримые признаки манеры: то, что считает скрипт, а не оценивает агент.

Трижды за одну работу повторилась одна ошибка — у модели спрашивали то, что
вычисляется. Сначала частота оборотов, потом границы блока «Нет у», потом эти
признаки: агент писал «типичная длина 2–5 слов» и «преобладают короткие
фразы», и проверяльщик выносил это грубой находкой двадцать восемь раз.

Считается по **выгрузке**, а не по раскладке агента. Раскладка — его работа, в
ней двух процентов сообщений уже не хватает, и счёт унаследовал бы пропуск.

Каждый признак говорит, точен он или приблизителен, и каким правилом получен.
Приблизительное, выданное за точное, вводит в заблуждение сильнее, чем честное
«посчитано вот так, вот что не вошло».
"""

import re
import statistics
from datetime import datetime

from .verify import OWNER

# Буквы, которых в русском нет. Нужны здесь ровно для одного — отличить
# кириллицу от латиницы. Мерить ими казахский нельзя: спецбуквы нашлись в 18
# сообщениях из 70 441, а казахских слов больше тысячи — владелец пишет
# обычной кириллицей.
#
# Списком слов казахский тоже не меряется, и приветствие тоже. Список неполон
# по устройству, а неполный список — это суждение, выданное за счёт. Язык и
# приветствие читает агент: он видит «озымыз гой» и «Йоу», которых списку не
# поймать. Скрипту остаётся механическое.
KAZAKH = set("әғқңөұүһіƏҒҚҢӨҰҮҺІ")

# Диапазоны шире базовых: ⭐ (U+2B50), ⏰ и прочие часы (U+2300–23FF), ‼ и ⁉
# раньше не покрывались — сообщение с ними считалось «без эмодзи», а «Ты
# где? ⭐» терял вопрос в конце, потому что хвостовой знак не отрезался.
EMOJI = re.compile(
    "[\U0001F300-\U0001FAFF\U00002600-\U000027BF\U0001F1E6-\U0001F1FF"
    "\U00002300-\U000023FF\U00002B00-\U00002BFF\U0000203C\U00002049❤️]"
)
LATIN = re.compile(r"[a-z]", re.I)
CYRILLIC = re.compile("[а-яёА-ЯЁ]|[" + "".join(sorted(KAZAKH)) + "]")

BASKETS = (("1–2", 1, 2), ("3–5", 3, 5), ("6–15", 6, 15), ("16+", 16, 10**6))


def _words(text):
    return len([one for one in re.split(r"\s+", text.strip()) if one])


def _smiles(text):
    """Скобка-смайл: закрывающих больше, чем открывающих.

    Правило «буква перед скобкой в конце» записывало в смайлы обычную скобку —
    «буду позже (наверное)». Смайл — это неуравновешенная скобка.
    """
    return text.count(")") > text.count("(")


def _minutes(day, time):
    """Минуты от эпохи — настоящим календарём.

    Счёт с месяцем в 31 день завышал задержку через границу месяца на сутки и
    больше: два часа в ночь на первое число уезжали в «позже суток», при
    пометке признака «точно».
    """
    moment = datetime.strptime(f"{day} {time}", "%Y-%m-%d %H:%M")
    return int(moment.timestamp() // 60)


def _turns(rows):
    """Заходы владельца: всё, что он написал, пока собеседник молчал.

    Считая сообщения, а не заходы, получим «дробит всегда» у любого, кто
    написал две строки подряд.
    """
    заходы, текущий = [], []
    for day, time, who, body in rows:
        if who == OWNER:
            текущий.append((day, time, body))
        elif текущий:
            заходы.append(текущий)
            текущий = []
    if текущий:
        заходы.append(текущий)
    return заходы


def turn_sizes(batches):
    """Размер захода у каждого сообщения владельца.

    Дробление, посчитанное на регистр, не отвечает на вопрос «этот оборот
    уходит одним сообщением или серией?» — по размерам заходов это считается
    для цитат каждого блока.

    Ключей два вида: (день, время, первая строка) и (день, None, первая
    строка) — половина цитат собранного файла стоит без времени. Минута и
    текст не различают чаты, поэтому размеры копятся множеством: молча выбрать
    один — значит соврать.
    """
    размеры = {}
    for batch in batches:
        for заход in _turns(batch.rows):
            for day, time, body in заход:
                строка = (body.splitlines() or [""])[0].strip()
                размеры.setdefault((day, time, строка), set()).add(len(заход))
                размеры.setdefault((day, None, строка), set()).add(len(заход))
    return размеры


def _delays(rows):
    """Сколько минут владелец молчал перед ответом на входящее."""
    задержки, ждёт = [], None
    for day, time, who, _ in rows:
        if who != OWNER:
            if ждёт is None:
                ждёт = _minutes(day, time)
        elif ждёт is not None:
            задержки.append(_minutes(day, time) - ждёт)
            ждёт = None
    return задержки


def measure(batch):
    """Признаки манеры по выгрузке. У каждого — точность и правило."""
    свои = [(day, time, body) for day, time, who, body in batch.rows if who == OWNER]
    слова = [_words(body) for _, _, body in свои]
    корзины = {
        имя: sum(1 for одно in слова if низ <= одно <= верх)
        for имя, низ, верх in BASKETS
    }
    заходы = _turns(batch.rows)
    задержки = _delays(batch.rows)
    return {
        "сообщений владельца": len(свои),
        "длина": {
            "медиана слов": int(statistics.median(слова)) if слова else 0,
            "корзины": корзины,
            "точно": True,
            "правило": "слова считаются по пробелам, многострочное сообщение целиком",
        },
        "дробление": {
            "заходов": len(заходы),
            "дроблёных": sum(1 for один in заходы if len(один) > 1),
            "самая длинная серия": max((len(один) for один in заходы), default=0),
            "точно": True,
            "правило": "заход — всё, что владелец написал, пока собеседник молчал",
        },
        "эмодзи": {
            "с эмодзи": sum(1 for _, _, body in свои if EMOJI.search(body)),
            "со скобками": sum(
                1 for _, _, body in свои
                if _smiles(body) and not EMOJI.search(body)
            ),
            "точно": True,
            "правило": "эмодзи — знаки Unicode Emoji; скобки-смайлы считаются отдельно, это типографика",
        },
        "латиница": {
            "сообщений": sum(
                1 for _, _, body in свои
                if LATIN.search(body) and not CYRILLIC.search(body)
            ),
            "точно": True,
            "правило": "ни одной кириллической буквы в сообщении",
        },
        "вопрос": {
            "в конце": sum(1 for _, _, body in свои if EMOJI.sub("", body).strip().endswith("?")),
            "внутри": sum(
                1 for _, _, body in свои
                if "?" in body and not EMOJI.sub("", body).strip().endswith("?")
            ),
            "точно": True,
            "правило": "хвостовые эмодзи и пробелы отбрасываются перед проверкой",
        },
        "задержка": {
            "медиана минут": int(statistics.median(задержки)) if задержки else 0,
            "в ту же минуту": sum(1 for одна in задержки if одна == 0),
            "позже суток": sum(1 for одна in задержки if одна > 1440),
            "ответов всего": len(задержки),
            "точно": True,
            "правило": "время от первого неотвеченного входящего до ответа владельца",
        },
    }


def report(признаки):
    """Признаки человеку и агенту в руки, с пометкой точности у каждого."""
    строки = [f"Сообщений владельца: {признаки['сообщений владельца']}", ""]
    for имя, свои in признаки.items():
        if not isinstance(свои, dict):
            continue
        метка = "точно" if свои.get("точно") else "приблизительно"
        строки.append(f"## {имя} ({метка})")
        for ключ, значение in свои.items():
            if ключ in ("точно", "правило"):
                continue
            строки.append(f"  {ключ}: {значение}")
        строки.append(f"  правило: {свои['правило']}")
        строки.append("")
    return "\n".join(строки)


def total(batches):
    """Признаки по всему корпусу сразу, а не сложенные побатчево.

    Складывал медианы по девяноста пяти батчам и получил «медиана слов: 314».
    Медиана не складывается: её надо считать по всем сообщениям разом.

    И доля берётся от своей единицы. Дроблёных заходов столько-то **из
    заходов**, дней с приветствием — **из дней**, ответов в ту же минуту — из
    ответов. Считая всё от числа сообщений, получали «заходов 41% из 70 441» —
    строку, не значащую ничего.
    """
    слова, задержки, заходы = [], [], []
    свои = 0
    эмодзи = скобки = вопрос_в_конце = вопрос_внутри = 0
    латиницей = 0
    корзины = {имя: 0 for имя, _, _ in BASKETS}
    for batch in batches:
        мои = [(day, time, body) for day, time, who, body in batch.rows if who == OWNER]
        свои += len(мои)
        слова += [_words(body) for _, _, body in мои]
        for имя, низ, верх in BASKETS:
            корзины[имя] += sum(1 for _, _, b in мои if низ <= _words(b) <= верх)
        заходы += _turns(batch.rows)
        задержки += _delays(batch.rows)
        эмодзи += sum(1 for _, _, b in мои if EMOJI.search(b))
        скобки += sum(1 for _, _, b in мои if _smiles(b) and not EMOJI.search(b))
        вопрос_в_конце += sum(1 for _, _, b in мои if EMOJI.sub("", b).strip().endswith("?"))
        вопрос_внутри += sum(
            1 for _, _, b in мои if "?" in b and not EMOJI.sub("", b).strip().endswith("?")
        )
        латиницей += sum(1 for _, _, b in мои if LATIN.search(b) and not CYRILLIC.search(b))
    образец = measure(batches[0]) if batches else {}
    правило = lambda имя: образец.get(имя, {}).get("правило", "")
    точно = lambda имя: образец.get(имя, {}).get("точно", True)
    return {
        "сообщений владельца": свои,
        "длина": {
            "медиана слов": int(statistics.median(слова)) if слова else 0,
            **корзины,
            "из": "сообщений",
            "точно": True,
            "правило": правило("длина"),
        },
        "дробление": {
            "заходов": len(заходы),
            "дроблёных": sum(1 for один in заходы if len(один) > 1),
            "самая длинная серия": max((len(один) for один in заходы), default=0),
            "из": "заходов",
            "точно": True,
            "правило": правило("дробление"),
        },
        "эмодзи": {
            "с эмодзи": эмодзи, "со скобками": скобки,
            "из": "сообщений", "точно": True, "правило": правило("эмодзи"),
        },
        "вопрос": {
            "в конце": вопрос_в_конце, "внутри": вопрос_внутри,
            "из": "сообщений", "точно": True, "правило": правило("вопрос"),
        },
        "латиница": {
            "сообщений": латиницей,
            "из": "сообщений", "точно": True, "правило": правило("латиница"),
        },
        "задержка": {
            "медиана минут": int(statistics.median(задержки)) if задержки else 0,
            "в ту же минуту": sum(1 for одна in задержки if одна == 0),
            "позже суток": sum(1 for одна in задержки if одна > 1440),
            "ответов всего": len(задержки),
            "из": "ответов",
            "точно": True,
            "правило": правило("задержка"),
        },
    }
