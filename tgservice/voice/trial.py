"""Замер файла стиля по отложенной выборке — третья спека.

Агент получает входящее, сведения о собеседнике и файл стиля. Пишет ответ.
Написанное сравнивается с настоящим ответом владельца по признакам, которые
поддаются измерению.

**Сравнение по смыслу сюда не входит.** Агент не знает обстоятельств и ответит
по существу иначе: владелец знал, что встреча в МЕГЕ, а агент не знает. Мерить
это значит мерить осведомлённость, а не манеру. Проверяется звучание.

Разделение труда то же, что во всей работе: скрипт считает механическое —
сколько сообщений, сколько слов, есть ли эмодзи, кончается ли вопросом, вся ли
строка латиницей. Приветствие, язык и обращение читает агент: список слов для
них неполон по устройству, а неполный список — это суждение, выданное за счёт.

Тип отношений агент определяет сам, по переписке, — как в настоящей работе.
Готовым даётся только смысл ответа: без него замер мерил бы осведомлённость,
а не манеру. Подробнее — в докстринге `case`.
"""

import re

from .traits import BASKETS, EMOJI, _words
from .traits import CYRILLIC, LATIN
from .compose import quotes as _style_quotes

# Первая строка цитаты файла стиля: отметка, «я:», текст. Время необязательно:
# без этого банк не видел цитат вида «2025-11-07 я: …», и дословная
# подстановка такой цитаты агентом замера не ловилась.
QUOTE = re.compile(r"^\s*\d{4}-\d{2}-\d{2}(?:\s+\d{2}:\d{2})?\s+я:\s?(?P<text>.*)$")


def case(обмен, смысл):
    """Задание агенту по одному обмену: кому, что было, входящее и смысл.

    **Тип отношений не даётся.** Первая редакция давала его готовым, и замер
    мерил только исполнение. В работе группу агенту никто не подскажет — он
    читает переписку и узнаёт регистр сам, и это часть того, что проверяется.

    **Смысл даётся готовым.** Первый замер этим и подкосился: агент придумывал
    содержание, которого знать не мог — что владелец хочет занять налички, что
    собеседник ему незнаком. Расхождение по смыслу тянуло за собой расхождение
    по признакам: длина, дробление и вопрос в конце меняются от того, ЧТО
    говоришь, а не только КАК.

    Ответа владельца в задании нет: показать его — значит отдать ответ на
    экзамене.
    """
    кто = обмен["chat"] + (f" (@{обмен['username']})" if обмен.get("username") else "")
    вид = "групповой чат" if обмен["kind"] == "group" else "личная переписка"
    строки = [
        "# Кому пишем",
        "",
        f"Собеседник: {кто}",
        f"Где: {вид}",
        f"Сообщений с ним за год: {обмен['chat_msgs']}",
        "",
    ]
    if обмен["context"]:
        строки += ["# Что было перед этим", ""]
        строки += [_реплика(row, обмен["chat"]) for row in обмен["context"]]
        строки.append("")
    строки += ["# Входящее — на него отвечаем", ""]
    строки += [_реплика(row, обмен["chat"]) for row in обмен["incoming"]]
    строки += ["", "# Что надо донести", "", смысл]
    return "\n".join(строки)


def _реплика(row, чат):
    кто = "я" if row["out"] else (row.get("from") or чат)
    return f"{row['date'][11:16]} {кто}: {row['text']}"


def measure(сообщения):
    """Признаки ответа, которые считает скрипт.

    Единица — весь ответ целиком, а не отдельное сообщение: владелец дробит
    одну мысль на несколько строк, и мерить их порознь значит мерить не то.
    """
    целиком = " ".join(сообщения)
    последнее = сообщения[-1] if сообщения else ""
    return {
        "сообщений": len(сообщения),
        "слов": _words(целиком),
        "эмодзи": bool(EMOJI.search(целиком)),
        "вопрос в конце": EMOJI.sub("", последнее).strip().endswith("?"),
        "латиницей": bool(LATIN.search(целиком)) and not CYRILLIC.search(целиком),
    }


def _basket(слов):
    """Корзина длины. Разница между тремя словами и четырьмя не значит ничего."""
    for имя, низ, верх in BASKETS:
        if низ <= слов <= верх:
            return имя
    return BASKETS[0][0]


def compare(агент, владелец):
    """Сошлось ли по каждому признаку. Точное число не сравнивается нигде.

    Дробление — «разбит или нет», а не «сколько именно»: два сообщения против
    трёх это одна и та же манера. Длина — корзиной: медиана владельца три
    слова, и три против четырёх это не разница.
    """
    return {
        "дробление": (агент["сообщений"] > 1) == (владелец["сообщений"] > 1),
        "длина": _basket(агент["слов"]) == _basket(владелец["слов"]),
        "эмодзи": агент["эмодзи"] == владелец["эмодзи"],
        "вопрос в конце": агент["вопрос в конце"] == владелец["вопрос в конце"],
        "латиницей": агент["латиницей"] == владелец["латиницей"],
    }


def floor(ответы):
    """Насколько владелец сходится сам с собой: доля совпадений по каждой паре.

    Спека: заранее выбранный порог был бы выдумкой — неизвестно, насколько
    стабильна манера от письма к письму. Опора — разброс между двумя
    настоящими ответами. Он и задаёт предел точности: точнее самого себя агент
    быть не может, и «сошлось 60%» без этого числа не значит ничего.

    Считаются все пары, а не случайная: одна пара — это n=1, а на n=1 уже
    обжигались, приняв везение за эффект правки.
    """
    признаки = [measure(один) for один in ответы if один]
    if len(признаки) < 2:
        return {}
    счёт, пар = {}, 0
    for место, один in enumerate(признаки):
        for другой in признаки[место + 1 :]:
            пар += 1
            for имя, сошлось in compare(один, другой).items():
                счёт[имя] = счёт.get(имя, 0) + bool(сошлось)
    return {имя: число / пар for имя, число in счёт.items()}


ВЕРДИКТ = re.compile(
    r"^\s*(?P<кто>[АБ])\s*\|\s*приветствие:\s*(?P<привет>\S+)"
    r"\s*\|\s*язык:\s*(?P<язык>\S+)"
    r"\s*\|\s*обращение:\s*(?P<обращение>\S+)",
    re.M,
)


def blind(обмен, агент, владелец):
    """Случай судье: два ответа под буквами, без указания, чей какой.

    Знай судья автора — засчитал бы настоящему то, чего не засчитал бы
    второму, и замер померил бы вежливость судьи.

    Тасовка считается от идентификатора чата, а не случайно: замер обязан
    повторяться, иначе перегон меряет заодно и жребий.
    """
    первым_агент = sum(ord(one) for one in обмен["chat_id"]) % 2 == 0
    пары = [("А", агент if первым_агент else владелец), ("Б", владелец if первым_агент else агент)]
    строки = ["Входящее:"]
    строки += [f"  {row['text']}" for row in обмен["incoming"]]
    for буква, ответ in пары:
        строки += ["", f"Ответ {буква}:"] + [f"  {one}" for one in ответ]
    return {
        "текст": "\n".join(строки),
        "чей": {
            "А": "агент" if первым_агент else "владелец",
            "Б": "владелец" if первым_агент else "агент",
        },
    }


def verdicts(ответ):
    """Что сказал судья про каждую букву."""
    разобрано = {}
    for one in ВЕРДИКТ.finditer(ответ):
        разобрано[one.group("кто")] = {
            "приветствие": one.group("привет").lower().startswith("ест"),
            "язык": one.group("язык").lower().strip(".,"),
            "обращение": one.group("обращение").lower().startswith("ест"),
        }
    return разобрано


def bank(файл):
    """Обороты файла стиля дословно: то, что агент может подставить готовым."""
    найдено = set()
    for цитата in _style_quotes(файл):
        head = QUOTE.match(цитата.splitlines()[0])
        if head and head.group("text").strip():
            найдено.add(head.group("text").strip())
    return найдено


def lifted(сообщения, банк):
    """Обороты, взятые из файла дословно.

    Спека: в выборку входят сообщения, под которые готового оборота нет. Агент
    должен написать своими словами в найденной манере, и подстановка цитаты не
    к месту считается провалом, даже когда все измеримые признаки сошлись.
    """
    return [one.strip() for one in сообщения if one.strip() in банк]
